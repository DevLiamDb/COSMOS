def parse_items(text):
    """Extract the JSON list from an LLM answer; keep only well-formed items."""
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S)
    m = re.search(r"\[.*\]", text, flags=re.S)
    if not m:
        return []
    try:
        items = json.loads(m.group(0))
    except json.JSONDecodeError:
        # salvage the complete objects of a list cut by the token limit
        items = []
        for obj in re.findall(r"\{[^{}]*\}", m.group(0), flags=re.S):
            try:
                items.append(json.loads(obj))
            except json.JSONDecodeError:
                pass
    good = []
    for it in items if isinstance(items, list) else []:
        if not isinstance(it, dict):
            continue
        mem, q = it.get("memory"), it.get("question")
        if isinstance(mem, str) and isinstance(q, str) and len(mem) > 15 and len(q) > 8:
            good.append({k: (v.strip() if isinstance(v, str) else None) for k, v in it.items()
                         if k in ("memory", "question", "update", "update_question", "absent_question")})
    return good


def cmd_gen(a):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    os.makedirs(DATA, exist_ok=True)
    rng = random.Random(1000 + a.shard)
    jobs = []
    for i in range(a.prompts):
        lang = "fr" if rng.random() < a.fr_share else "en"
        jobs.append((lang, TOPICS[(i * 7 + rng.randrange(len(TOPICS))) % len(TOPICS)]))
    jobs = jobs[a.shard::a.shards]
    tok = AutoTokenizer.from_pretrained(a.llm)
    tok.padding_side = "left"
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    cuda = torch.cuda.is_available()
    model = AutoModelForCausalLM.from_pretrained(a.llm, dtype=torch.float16 if cuda else torch.float32,
                                                 device_map={"": 0} if cuda else None).eval()
    path = os.path.join(DATA, f"raw_{a.shard}.jsonl")
    done = sum(1 for _ in open(path, encoding="utf-8")) if os.path.exists(path) else 0
    print(f"shard {a.shard}: {len(jobs)} prompts, {done} items already there", flush=True)
    t0, n_items = time.time(), 0
    with open(path, "a", encoding="utf-8") as f:
        for b in range(0, len(jobs), a.batch):
            batch = jobs[b:b + a.batch]
            texts = []
            for lang, topic in batch:
                msgs = [{"role": "user", "content": PROMPT[lang].format(topic=topic, n=a.per_prompt)}]
                try:
                    texts.append(tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True, enable_thinking=False))
                except TypeError:
                    texts.append(tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True))
            x = tok(texts, return_tensors="pt", padding=True, add_special_tokens=False).to(model.device)
            with torch.no_grad():
                out = model.generate(**x, max_new_tokens=a.max_new_tokens, do_sample=True, temperature=0.9, top_p=0.95,
                                     pad_token_id=tok.pad_token_id)
            for (lang, topic), seq in zip(batch, out):
                items = parse_items(tok.decode(seq[x["input_ids"].shape[1]:], skip_special_tokens=True))
                for it in items:
                    it.update(lang=lang, topic=topic, group=f"{a.shard}-{b}-{topic}")
                    f.write(json.dumps(it, ensure_ascii=False) + "\n")
                n_items += len(items)
            f.flush()
            el = time.time() - t0
            print(f"  {min(b + a.batch, len(jobs))}/{len(jobs)} prompts, {n_items} items, {el / 60:.1f} min", flush=True)


# ------------------------------------------------------------------ 1b. data written by Claude
INBOX = os.path.join(DATA, "claude_inbox")
KINDS = {"fact", "decision", "task", "preference", "project_context", "event", "person", "open_question"}


def _str(x, lo=1):
    return isinstance(x, str) and len(x.strip()) >= lo


def check_claude_item(it):
    """Return a clean item, or None if a required field is missing or malformed."""
    if not isinstance(it, dict) or not _str(it.get("memory"), 12):
        return None
    qs = [q.strip() for q in (it.get("questions") or []) if _str(q, 4)]
    if not qs:
        return None
    upd = it.get("update") if _str(it.get("update"), 12) else None
    uqs = [q.strip() for q in (it.get("update_questions") or []) if _str(q, 4)] if upd else []
    if upd and not uqs:
        upd = None
    return {
        "memory": it["memory"].strip(), "questions": qs[:5], "update": upd, "update_questions": uqs[:4],
        "distractor": it["distractor"].strip() if _str(it.get("distractor"), 12) else None,
        "absent_question": it["absent_question"].strip() if _str(it.get("absent_question"), 4) else None,
        "lang": str(it.get("lang") or "?")[:5], "topic": str(it.get("theme") or "?"),
        "kind": it.get("kind") if it.get("kind") in KINDS else None,
        "group": "claude-" + str(it.get("id") or "x").split("-")[0],
    }


def cmd_ingest(a):
    """Read every saved Claude answer in training/data/claude_inbox/ and write training/data/raw_claude.jsonl."""
    files = sorted(glob.glob(os.path.join(INBOX, "*")))
    if not files:
        print(f"No file in {INBOX}: save each Claude answer there as a .txt file.")
        return
    out, seen, bad, langs = [], set(), 0, {}
    for fp in files:
        for line in open(fp, encoding="utf-8", errors="replace"):
            line = line.strip().rstrip(",")
            if not (line.startswith("{") and line.endswith("}")):
                continue
            try:
                it = check_claude_item(json.loads(line))
            except json.JSONDecodeError:
                it = None
            if it is None:
                bad += 1
                continue
            key = it["memory"].lower()
            if key in seen:
                continue
            seen.add(key)
            out.append(it)
            langs[it["lang"]] = langs.get(it["lang"], 0) + 1
    os.makedirs(DATA, exist_ok=True)
    with open(os.path.join(DATA, "raw_claude.jsonl"), "w", encoding="utf-8") as f:
        for it in out:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
    print(f"{len(files)} files, {len(out)} memories kept, {bad} malformed lines skipped")
    print("per language:", dict(sorted(langs.items(), key=lambda x: -x[1])))
    print("with an update:", sum(1 for it in out if it["update"]), "| with a distractor:", sum(1 for it in out if it["distractor"]))


# ------------------------------------------------------------------ 2. pairs
def benchmark_blocklist():
    """Proper names and values used by the COSMOS benchmark: generated data must not contain them."""
    sys.path.insert(0, ROOT)
    from benchmark import synth

    words = set(w.lower() for w in synth.FIRST + synth.CITIES)
    ds = json.load(open(os.path.join(ROOT, "benchmark", "dataset.json"), encoding="utf-8"))
    for f in ds["facts"]:
        for w in re.findall(r"\b[A-ZÀ-Ý][\wÀ-ÿ'-]{2,}", f["text"]):
            words.add(w.lower())
    # common sentence-start words are not names
    # keep names and specific values; drop ordinary words and common tech terms caught by the capital-letter rule
    words -= {"je", "mon", "ma", "mes", "le", "la", "les", "notre", "nous", "on", "il", "elle", "pour", "depuis", "en", "the",
              "code", "commits", "conventional", "décision", "j'ai", "question", "ram", "tâche", "tours", "nice", "ssl",
              "vps", "ubuntu", "kubernetes", "postgresql", "firebase", "stripe", "flutter"}
    return words


def as_stored(text):
    """A memory exactly as CosmosEngine.write_node embeds it (Surface + start of Abyss), so the
    model trains on the same passage text it will see in COSMOS."""
    sys.path.insert(0, ROOT)
    from cosmos import summarizer

    return f"{summarizer.summarize(text)} {text[:500]}"


def cmd_pairs(a):
    rows = []
    for p in sorted(glob.glob(os.path.join(DATA, "raw_*.jsonl"))):
        rows += [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]
    block = benchmark_blocklist()
    tokens = lambda s: set(re.findall(r"[\wÀ-ÿ'-]+", (s or "").lower()))
    kept, dropped, seen = [], 0, set()
    for r in rows:
        txt = " ".join([r.get(k) or "" for k in ("memory", "question", "update", "update_question", "distractor")]
                       + (r.get("questions") or []) + (r.get("update_questions") or []))
        key = (r["memory"] or "").lower()
        if tokens(txt) & block or key in seen:
            dropped += 1
            continue
        seen.add(key)
        kept.append(r)
    print(f"{len(rows)} generated items, {dropped} dropped (benchmark names or duplicates), {len(kept)} kept")

    by_group = {}
    for r in kept:
        by_group.setdefault(r["group"], []).append(r)
    rng = random.Random(7)
    groups = list(by_group)
    rng.shuffle(groups)
    n_dev = max(1, int(len(groups) * a.dev_share))
    split = {"dev": groups[:n_dev], "train": groups[n_dev:]}

    for name, gs in split.items():
        out = []
        for g in gs:
            items = by_group[g]
            for i, r in enumerate(items):
                others = [o for j, o in enumerate(items) if j != i]
                neg_topic = rng.choice(others)["memory"] if others else None
                qs = r.get("questions") or ([r["question"]] if r.get("question") else [])
                uqs = r.get("update_questions") or ([r["update_question"]] if r.get("update_question") else [])
                near = r.get("distractor") or neg_topic          # best hard negative: a near-miss memory
                if not near:
                    continue
                # Both versions of a fact are right answers for the embedding: COSMOS picks the newest
                # one by date (recency bonus + `obsolete` flag). Using the old version as a negative
                # taught the model to avoid the closest match, and broke paraphrase/history questions.
                for q in qs:
                    out.append({"anchor": q, "positive": r["memory"], "negative": near, "kind": "direct"})
                if r.get("update"):
                    for q in uqs:
                        out.append({"anchor": q, "positive": r["update"], "negative": near, "kind": "update"})
        rng.shuffle(out)
        for o in out:
            o["positive"], o["negative"] = as_stored(o["positive"]), as_stored(o["negative"])
        p = os.path.join(DATA, f"{name}.jsonl")
        with open(p, "w", encoding="utf-8") as f:
            for o in out:
                f.write(json.dumps(o, ensure_ascii=False) + "\n")
        kinds = {}
        for o in out:
            kinds[o["kind"]] = kinds.get(o["kind"], 0) + 1
        print(f"{name}: {len(out)} triplets {kinds} -> {p}")


