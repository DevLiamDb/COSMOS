def cmd_train(a):
    from datasets import load_dataset
    from sentence_transformers import SentenceTransformer, SentenceTransformerTrainer, SentenceTransformerTrainingArguments
    try:  # sentence-transformers >= 6
        from sentence_transformers.sentence_transformer.evaluation import TripletEvaluator
        from sentence_transformers.sentence_transformer.losses import MultipleNegativesRankingLoss
        from sentence_transformers.sentence_transformer.training_args import BatchSamplers
    except ImportError:  # older versions
        from sentence_transformers.evaluation import TripletEvaluator
        from sentence_transformers.losses import MultipleNegativesRankingLoss
        from sentence_transformers.training_args import BatchSamplers

    cols = ["anchor", "positive", "negative"]
    train = load_dataset("json", data_files=os.path.join(DATA, "train.jsonl"), split="train").select_columns(cols)
    dev = load_dataset("json", data_files=os.path.join(DATA, "dev.jsonl"), split="train").select_columns(cols)
    if a.limit:
        train = train.select(range(min(a.limit, len(train))))
        dev = dev.select(range(min(max(8, a.limit // 5), len(dev))))
    qp, pp = prefixes_for(a.base)
    add_prefixes = lambda r: {"anchor": qp + r["anchor"], "positive": pp + r["positive"], "negative": pp + r["negative"]}
    train, dev = train.map(add_prefixes), dev.map(add_prefixes)
    # some bases ship bf16 weights: fp16 AMP on a T4 cannot unscale bf16 gradients, so train in fp32
    model = SentenceTransformer(a.base).float()
    model.max_seq_length = 256
    ev = TripletEvaluator(dev["anchor"], dev["positive"], dev["negative"], name="dev")
    print("before:", ev(model), flush=True)
    out_dir = os.path.join(OUT, "cosmos-embed")
    args = SentenceTransformerTrainingArguments(
        output_dir=os.path.join(OUT, "checkpoints"), num_train_epochs=a.epochs, per_device_train_batch_size=a.batch,
        learning_rate=a.lr, warmup_ratio=0.1, fp16=a.fp16, batch_sampler=BatchSamplers.NO_DUPLICATES,
        eval_strategy="epoch", save_strategy="no", logging_steps=20, report_to="none", seed=42,
    )
    trainer = SentenceTransformerTrainer(model=model, args=args, train_dataset=train, eval_dataset=dev,
                                         loss=MultipleNegativesRankingLoss(model), evaluator=ev)
    trainer.train()
    print("after:", ev(model), flush=True)
    model.save(out_dir)
    json.dump([qp, pp], open(os.path.join(out_dir, "cosmos_prefixes.json"), "w", encoding="utf-8"))
    print("saved", out_dir)


# ------------------------------------------------------------------ 4. COSMOS benchmark
def bench(model_path, out_dir, recency=None):
    """Run the COSMOS level-1 benchmark with a sentence-transformers model in place of the default one."""
    import numpy as np
    from sentence_transformers import SentenceTransformer

    sys.path.insert(0, ROOT)
    import cosmos.embeddings as E
    import benchmark.run as R

    st = SentenceTransformer(model_path).float()  # same precision for the base and the fine-tuned model

    class M:
        def embed(self, texts):
            for v in st.encode(list(texts), normalize_embeddings=True, convert_to_numpy=True):
                yield np.asarray(v, dtype=np.float32)

    E._model = M()
    E.EMBEDDING_DIM = st.get_sentence_embedding_dimension()
    E.QUERY_PREFIX, E.PASSAGE_PREFIX = prefixes_for(model_path)
    if recency is not None:
        import cosmos.graph as G
        q = G.CosmosEngine.query
        G.CosmosEngine.query = lambda self, text, top_k=5, session_id=None, recency_weight=recency: q(self, text, top_k, session_id, recency_weight)
    argv = sys.argv
    sys.argv = ["run", "--scales", "100", "--seeds", "0,1,2", "--out", out_dir]
    try:
        R.main()
    finally:
        sys.argv = argv
    s = json.load(open(os.path.join(out_dir, "niveau1.json"), encoding="utf-8"))["summary"]["100"]["niveau1"]
    return {k: round(v[0], 4) for k, v in s.items() if isinstance(v, list)}


def cmd_eval(a):
    import subprocess

    res = {}
    models = (("minilm", MINILM), ("base", a.base), ("cosmos-embed", os.path.join(OUT, "cosmos-embed")))
    for name, path in models:
        d = os.path.join(OUT, f"bench_{name}")
        # one process per model: COSMOS caches the category prototypes of the first model it sees
        subprocess.run([sys.executable, __file__, "_bench", path, d], cwd=ROOT, check=True)
        res[name] = json.load(open(os.path.join(d, "metrics.json"), encoding="utf-8"))
    json.dump(res, open(os.path.join(OUT, "eval.json"), "w", encoding="utf-8"), indent=1)
    keys = ["recall@1", "recall@3", "recall@5", "mrr", "update_acc", "abstention_best_acc", "categorisation_acc"]
    print(f"{'metric':22}" + "".join(f"{name:>15}" for name, _ in models))
    for k in keys:
        cells = [res[name].get(k) for name, _ in models]
        print(f"{k:22}" + "".join(f"{v if v is None else round(v * 100, 1):>15}" for v in cells))


def cmd__bench(a):
    m = bench(a.model, a.out)
    json.dump(m, open(os.path.join(a.out, "metrics.json"), "w", encoding="utf-8"), indent=1)


