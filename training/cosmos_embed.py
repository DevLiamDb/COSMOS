"""COSMOS-Embed: our own embedding model for COSMOS, by full fine-tuning.

Base model : intfloat/multilingual-e5-small (MIT) -- needs the "query: " / "passage: " prefixes
Our data   : question -> memory pairs generated by an LLM, with hard negatives
             (an older version of the same fact, a memory on the same topic).
Judge      : the COSMOS retrieval benchmark (benchmark/run.py, no LLM), which
             never sees the training data (its names and phrasings are filtered out).

Steps (each one is a subcommand, run from the COSMOS/ folder):
  gen    generate memories + questions with an LLM          -> training/data/raw_*.jsonl
  ingest read the answers saved from Claude (CLAUDE_DATA_PROMPT.md) -> training/data/raw_claude.jsonl
  pairs  build (question, memory, hard negative) triplets    -> training/data/train.jsonl, dev.jsonl
  train  full fine-tuning with MultipleNegativesRankingLoss  -> training/out/cosmos-embed
  eval   COSMOS benchmark: base vs our model                 -> training/out/eval.json
"""
