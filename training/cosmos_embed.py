# (query prefix, passage prefix) the model expects; e5 scores collapse without them
PREFIXES = {"intfloat/multilingual-e5-small": ("query: ", "passage: ")}


def prefixes_for(model_path):
    """Prefixes of a base model, or the ones saved next to a fine-tuned model by cmd_train."""
    saved = os.path.join(model_path, "cosmos_prefixes.json")
    if os.path.exists(saved):
        return tuple(json.load(open(saved, encoding="utf-8")))
    return PREFIXES.get(model_path, ("", ""))

